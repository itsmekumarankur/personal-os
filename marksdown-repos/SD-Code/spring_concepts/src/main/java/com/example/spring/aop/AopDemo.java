package com.example.spring.aop;

import org.aspectj.lang.ProceedingJoinPoint;
import org.aspectj.lang.annotation.Around;
import org.aspectj.lang.annotation.Aspect;
import org.springframework.context.annotation.AnnotationConfigApplicationContext;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.EnableAspectJAutoProxy;
import org.springframework.stereotype.Component;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * The code teaches Spring AOP. 
   - Cross-cutting work like audit, timing, security and retries lives in one aspect instead of being copied into every method. 
   - Spring does this by wrapping your bean in a proxy: 
       callers talk to the proxy, the proxy runs the advice, then calls your real method. 
  Key learning: Spring uses a Proxy (middleman) to run this extra logic before and after the actual method
    * ================================================================
    * AOP (ASPECT ORIENTED PROGRAMMING) - THE BIG IDEA
    * ================================================================
    *
    *   Problem: audit / timing / security / retry code copy-pasted
    *            into every service method.
    *
    *   Solution: write it ONCE in an ASPECT. Spring wraps the bean
    *             in a PROXY that runs the aspect around your method.
    *
    *   Same mechanism behind: @Transactional, @Cacheable,
    *                          @Async, @Retryable
    *
    * ================================================================
    * THE PIECES
    * ================================================================
    *
    *   @Audited("FUND_TRANSFER")      marker annotation on a method
    *   TransferService                the real business class
    *   AuditAspect  @Around           the advice (before + after)
    *   @EnableAspectJAutoProxy        turns the proxy magic ON
    *
    * ================================================================
    * HOW A CALL FLOWS THROUGH THE PROXY
    * ================================================================
    *
    *   caller (main)
    *       |
    *       |  ctx.getBean(TransferService.class)
    *       |  -> gets the PROXY, not the real object
    *       v
    *   +-------------------------------+
    *   |            PROXY              |
    *   |  (generated by Spring)        |
    *   |                               |
    *   |  has @Audited annotation?     |
    *   +---------------+---------------+
    *                   |
    *         +---------+-----------+
    *         | YES                 | NO
    *         v                     v
    *   +--------------------+   call real method
    *   | AuditAspect        |   directly
    *   |  >> before         |   (no advice)
    *   |  start timer       |
    *   |  pjp.proceed() ----+--+
    *   |  << after (finally)|  |
    *   +---------^----------+  |
    *             |             v
    *             |      +----------------+
    *             +------| REAL METHOD    |
    *                    | business logic |
    *                    +----------------+
    *

 */
public class AopDemo {

    @Retention(RetentionPolicy.RUNTIME)
    @Target(ElementType.METHOD)
    @interface Audited {
        String value();
    }

    @Component
    static class TransferService {

        @Audited("FUND_TRANSFER")
        public String transfer(String from, String to, int amount) {
            System.out.println("    business logic: moving " + amount + " from " + from + " to " + to);
            return "OK";
        }

        public void notAudited() {
            System.out.println("    business logic: no annotation, so no advice");
        }

        @Audited("SELF_CALL")
        public void audited() {
            System.out.println("    business logic: audited method");
        }

        public void callsAuditedViaThis() {
            this.audited(); // 'this' is the real object, NOT the proxy -> advice is skipped
        }
    }

    @Aspect
    @Component
    static class AuditAspect {

        @Around("@annotation(audited)")
        public Object audit(ProceedingJoinPoint pjp, Audited audited) throws Throwable {
            String method = pjp.getSignature().getName();
            System.out.println("  >> [" + audited.value() + "] before " + method);
            long start = System.nanoTime();
            try {
                return pjp.proceed(); // call the real method
            } finally {
                long micros = (System.nanoTime() - start) / 1_000;
                System.out.println("  << [" + audited.value() + "] after " + method + " (" + micros + " us)");
            }
        }
    }

    @Configuration
    @EnableAspectJAutoProxy
    static class AopConfig {
    }

    public static void main(String[] args) {
        try (var ctx = new AnnotationConfigApplicationContext(
                AopConfig.class, TransferService.class, AuditAspect.class)) {

            TransferService service = ctx.getBean(TransferService.class);
            System.out.println("Bean class is a proxy: " + service.getClass().getSimpleName());

            System.out.println("1) annotated method:");
            service.transfer("ACC-1", "ACC-2", 500);

            System.out.println("2) method without annotation:");
            service.notAudited();

            System.out.println("3) self-invocation through 'this' (advice silently skipped):");
            service.callsAuditedViaThis();

            /**
                * ================================================================
                * THE 3 CALLS IN main()
                * ================================================================
                *
                *  1) ANNOTATED METHOD     service.transfer("ACC-1","ACC-2",500)
                *
                *     caller -> proxy -> aspect -> real transfer()
                *
                *     >> [FUND_TRANSFER] before transfer
                *        business logic: moving 500 from ACC-1 to ACC-2
                *     << [FUND_TRANSFER] after transfer (N us)
                *
                *  2) NO ANNOTATION        service.notAudited()
                *
                *     caller -> proxy -> real notAudited()    (aspect skipped)
                *
                *        business logic: no annotation, so no advice
                *
                *  3) SELF-INVOCATION      service.callsAuditedViaThis()
                *
                *     caller -> proxy -> real
                * 
            */
        }
    }
}
